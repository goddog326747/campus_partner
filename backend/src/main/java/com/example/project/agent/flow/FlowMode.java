package com.example.project.agent.flow;

/**
 * Agent Flow 执行模式
 * 
 * ============================================================
 *                    两种核心执行模式
 * ============================================================
 * 
 * 【规划执行模式 - PLANNING】
 * 
 * 特点：
 * - 先规划所有步骤，再按顺序执行
 * - 执行路径在开始前就已确定
 * - 每个节点的输入输出预先定义
 * 
 * 适用场景：
 * - 确定性任务（如：生成帖子、数据报表）
 * - 需要严格控制的流程
 * - 可预见的执行路径
 * 
 * 执行流程：
 * 1. 分析输入 → 2. 生成执行计划 → 3. 按顺序执行 → 4. 返回结果
 * 
 * 示例：
 * 用户要求"生成一篇关于周末爬山的帖子"
 * 规划：查询用户风格 → 获取热门话题 → 生成内容 → 检查敏感词
 * 
 * 【ReAct 模式 - REACT】
 * 
 * ReAct = Reasoning (推理) + Acting (行动)
 * 
 * 特点：
 * - 边推理边执行
 * - 根据中间结果动态决定下一步
 * - 支持循环和回溯
 * 
 * 适用场景：
 * - 探索性任务（如：复杂问题解答、多轮对话）
 * - 需要动态调整策略的场景
 * - 不确定性较高的任务
 * 
 * 执行循环：
 * Thought (思考) → Action (行动) → Observation (观察) → ... → Answer (回答)
 * 
 * 示例：
 * 用户问"帮我找一下适合初学者的羽毛球拍"
 * Thought: 用户需要羽毛球拍推荐，我应该先了解用户预算和水平
 * Action: 询问用户预算
 * Observation: 用户回复"500元以内"
 * Thought: 预算确定，现在需要查询热门球拍
 * Action: 查询热门羽毛球拍
 * ...
 * 
 * ============================================================
 */
public enum FlowMode {
    
    /**
     * 规划执行模式
     * 
     * 先规划，后执行。适合确定性任务。
     */
    PLANNING,
    
    /**
     * ReAct 模式
     * 
     * 边推理边执行。适合探索性任务。
     */
    REACT,
    
    /**
     * 混合模式
     * 
     * 结合规划和 ReAct，在规划中支持动态调整。
     */
    HYBRID
}
